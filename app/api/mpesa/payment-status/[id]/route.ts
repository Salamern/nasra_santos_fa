import { createHash, timingSafeEqual } from "crypto";
import { NextResponse } from "next/server";
import { createAdminClient } from "@/lib/supabase/admin";

export const dynamic = "force-dynamic";

type RouteContext = {
  params: Promise<{ id: string }>;
};

function hashPaymentStatusToken(token: string) {
  return createHash("sha256").update(token).digest("hex");
}

function tokensMatch(
  suppliedToken: string,
  storedTokenHash: string
): boolean {
  try {
    const suppliedHash = hashPaymentStatusToken(suppliedToken);

    const suppliedBuffer = Buffer.from(suppliedHash, "hex");
    const storedBuffer = Buffer.from(storedTokenHash, "hex");

    if (suppliedBuffer.length !== storedBuffer.length) {
      return false;
    }

    return timingSafeEqual(suppliedBuffer, storedBuffer);
  } catch {
    return false;
  }
}

export async function GET(request: Request, context: RouteContext) {
  try {
    const { id } = await context.params;
    const paymentId = id?.trim();

    if (!paymentId) {
      return NextResponse.json(
        {
          success: false,
          message: "Payment ID is required.",
        },
        { status: 400 }
      );
    }

    /*
      The payment-status token must be supplied by the browser.

      Example:
      /api/mpesa/payment-status/<payment-id>?token=<private-token>

      The usable token itself is never stored in Supabase.
      Only its SHA-256 hash is stored.
    */
    const requestUrl = new URL(request.url);
    const paymentStatusToken =
      requestUrl.searchParams.get("token")?.trim() || "";

    if (!paymentStatusToken) {
      return NextResponse.json(
        {
          success: false,
          message: "Payment status authorization is required.",
        },
        { status: 401 }
      );
    }

    /*
      The token generated by stk-push is 32 random bytes represented
      as 64 hexadecimal characters.

      Reject obviously malformed values before querying the database.
    */
    if (!/^[a-f0-9]{64}$/i.test(paymentStatusToken)) {
      return NextResponse.json(
        {
          success: false,
          message: "Invalid payment status authorization.",
        },
        { status: 401 }
      );
    }

    const adminSupabase = createAdminClient();

    const { data: payment, error } = await adminSupabase
      .from("registration_payments")
      .select(`
          id,
          registration_id,
          player_name,
          payment_items,
          amount_expected,
          amount_paid,
          status,
          mpesa_receipt_number,
          result_code,
          result_description,
          transaction_date,
          created_at,
          updated_at,
          payment_status_token_hash
        `)
      .eq("id", paymentId)
      .maybeSingle();

    if (error) {
      console.error("Payment status lookup error:", error);

      return NextResponse.json(
        {
          success: false,
          message: "Unable to check payment status.",
        },
        { status: 500 }
      );
    }

    /*
      Return the same generic authorization response whether the
      payment ID does not exist or the token is wrong.

      This avoids giving an attacker useful information about which
      payment IDs are valid.
    */
    if (
      !payment ||
      !payment.payment_status_token_hash ||
      !tokensMatch(
        paymentStatusToken,
        String(payment.payment_status_token_hash)
      )
    ) {
      return NextResponse.json(
        {
          success: false,
          message: "Invalid payment status authorization.",
        },
        { status: 401 }
      );
    }

    return NextResponse.json(
      {
        success: true,

        payment: {
          id: payment.id,
          registrationId: payment.registration_id,
          playerName: payment.player_name,
          items: payment.payment_items ?? [],
          amountExpected: Number(payment.amount_expected ?? 0),
          amountPaid: Number(payment.amount_paid ?? 0),
          status: payment.status,
          mpesaReceiptNumber:
            payment.mpesa_receipt_number ?? null,
          resultCode: payment.result_code ?? null,
          resultDescription:
            payment.result_description ?? null,
          transactionDate: payment.transaction_date ?? null,
          createdAt: payment.created_at ?? null,
          updatedAt: payment.updated_at ?? null,
        },
      },
      {
        status: 200,
        headers: {
          "Cache-Control":
            "no-store, no-cache, must-revalidate, proxy-revalidate",
        },
      }
    );
  } catch (error) {
    console.error("Payment status API error:", error);

    return NextResponse.json(
      {
        success: false,
        message: "Unable to check payment status.",
      },
      { status: 500 }
    );
  }
}